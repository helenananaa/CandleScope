#[cfg(test)]
mod tests {
    use super::pine_unicode_block;

    #[test]
    fn resolves_java_style_block_aliases() {
        assert_eq!(pine_unicode_block("BasicLatin"), Some((0x0000, 0x007F)));
        assert_eq!(pine_unicode_block("basic_latin"), Some((0x0000, 0x007F)));
        assert_eq!(
            pine_unicode_block("Latin-1Supplement"),
            Some((0x0080, 0x00FF))
        );
        assert_eq!(
            pine_unicode_block("latin_1_supplement"),
            Some((0x0080, 0x00FF))
        );
        assert_eq!(pine_unicode_block("Greek"), Some((0x0370, 0x03FF)));
        assert_eq!(pine_unicode_block("GreekAndCoptic"), Some((0x0370, 0x03FF)));
        assert_eq!(pine_unicode_block("Basic-Latin"), None);
        assert_eq!(pine_unicode_block("NoSuchBlock"), None);
    }
}
