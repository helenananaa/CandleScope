import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { RunResultContractError } from "../../backtest/runResult/runResult.js";
import {
  parseStrategyRunCapabilities, parseStrategyRunStatus, StrategyRunContractError, strategyRunProfile,
} from "../../backtest/runResult/strategyRun.js";
import { StrategyDataManager, type StrategyDataApi } from "../manager/strategyDataManager.js";

function fixture(path: string): unknown {
  return JSON.parse(readFileSync(new URL(`../../../../tests/fixtures/${path}`, import.meta.url), "utf8"));
}

// Generated by the backend tests from what the run facade serves.
const HOST = fixture("run-result/host-bar-builtin.run-result.json");
const NATIVE = fixture("run-result/native-pine.run-result.json");
const STATUS = fixture("strategy-run/host-completed.strategy-run.json");
const MATRIX = fixture("strategy-run-capabilities/matrix.strategy-run-capabilities.json");

function api(overrides: Partial<StrategyDataApi> = {}): StrategyDataApi {
  return overrides as StrategyDataApi;
}

test("run results are read once per family and run, then served from the bounded cache", async () => {
  const calls: string[] = [];
  const manager = new StrategyDataManager(api({
    async getStrategyRunResult(runId) {
      calls.push(runId);
      return structuredClone(runId.startsWith("native_") ? NATIVE : HOST);
    },
  }));
  const host = await manager.loadRunResult("host", "bt_1");
  assert.equal(await manager.loadRunResult("host", "bt_1"), host);
  assert.equal((await manager.loadRunResult("native", "native_1")).authority, "SCRIPT");
  assert.deepEqual(calls, ["bt_1", "native_1"]);
  for (let index = 2; index <= 9; index += 1) await manager.loadRunResult("host", `bt_${index}`);
  assert.equal(manager.diagnostics().runResults, 8);
  await manager.loadRunResult("native", "native_1");
  assert.equal(calls.filter((call) => call === "native_1").length, 2, "the oldest entry was evicted");
  manager.dispose();
  assert.equal(manager.diagnostics().runResults, 0);
});

test("a result served under the wrong family is rejected instead of being drawn", async () => {
  const manager = new StrategyDataManager(api({ async getStrategyRunResult() { return structuredClone(HOST); } }));
  await assert.rejects(manager.loadRunResult("native", "native_1"), RunResultContractError);
  await assert.rejects(manager.loadRunResult("external", "native_1"), RunResultContractError);
  assert.equal(manager.diagnostics().runResults, 0, "rejected results are not cached");
  manager.dispose();
});

test("missing endpoints and aborted reads fail without caching", async () => {
  const bare = new StrategyDataManager(api());
  await assert.rejects(bare.loadRunResult("native", "native_1"), /unavailable/i);
  await assert.rejects(bare.loadRunStatus("bt_1"), /unavailable/i);
  await assert.rejects(bare.loadRunCapabilities(), /unavailable/i);
  bare.dispose();
  const manager = new StrategyDataManager(api({
    async getStrategyRunResult(_runId, signal) {
      await new Promise((resolve) => setTimeout(resolve, 5));
      signal?.throwIfAborted();
      return structuredClone(HOST);
    },
  }));
  const controller = new AbortController();
  const pending = manager.loadRunResult("host", "bt_1", controller.signal);
  controller.abort(new Error("consumer left"));
  await assert.rejects(pending);
  assert.equal(manager.diagnostics().runResults, 0);
  assert.equal(manager.diagnostics().operations, 0);
  manager.dispose();
});

test("run status is read fresh every time and must be the run that was asked for", async () => {
  let reads = 0;
  const manager = new StrategyDataManager(api({
    async getStrategyRun(runId) { reads += 1; return { ...structuredClone(STATUS) as object, run_id: runId }; },
    async cancelStrategyRun() { return structuredClone(STATUS); },
  }));
  const status = await manager.loadRunStatus("bt_1");
  assert.deepEqual([status.family, status.state, status.terminal, status.result_available], ["host", "COMPLETED", true, true]);
  await manager.loadRunStatus("bt_1");
  assert.equal(reads, 2);
  // The fixture's id is bt_fixture: a status for another run is refused.
  await assert.rejects(manager.cancelStrategyRun("bt_1"), StrategyRunContractError);
  assert.equal((await manager.cancelStrategyRun("bt_fixture")).run_id, "bt_fixture");
  manager.dispose();
});

test("the status contract rejects states that disagree with each other", () => {
  const status = structuredClone(STATUS) as Record<string, unknown>;
  assert.equal(parseStrategyRunStatus(status).clock_policy, "FIXED");
  assert.throws(() => parseStrategyRunStatus({ ...status, terminal: false }), /terminal/);
  assert.throws(() => parseStrategyRunStatus({ ...status, state: "RUNNING", terminal: false }), /result_available/);
  assert.throws(() => parseStrategyRunStatus({ ...status, state: "DONE" }), /state/);
  assert.throws(() => parseStrategyRunStatus({ ...status, family: "replay" }), /family/);
  assert.throws(() => parseStrategyRunStatus({ ...status, schema: "candlescope.strategy-run/2" }), /schema/);
  assert.deepEqual(parseStrategyRunStatus({ ...status, state: "FAILED", result_available: false,
    error: { code: "HOST_RESTARTED", message: null } }).error, { code: "HOST_RESTARTED", message: null });
});

test("one capability matrix names every family and profile, and is kept until refreshed", async () => {
  let reads = 0;
  const manager = new StrategyDataManager(api({ async strategyRunCapabilities() { reads += 1; return structuredClone(MATRIX); } }));
  const matrix = await manager.loadRunCapabilities();
  assert.equal(await manager.loadRunCapabilities(), matrix);
  await manager.loadRunCapabilities(undefined, { refresh: true });
  assert.equal(reads, 2);
  assert.deepEqual(Object.keys(matrix.families).sort(), ["continuous", "external", "host", "native"]);
  assert.equal(strategyRunProfile(matrix, "native", "pine")?.authority, "SCRIPT");
  assert.equal(strategyRunProfile(matrix, "native", "pine")?.fidelities, null);
  assert.equal(strategyRunProfile(matrix, "external", "pine")?.authority, "HOST");
  assert.deepEqual(strategyRunProfile(matrix, "continuous", "builtin")?.starts, ["HISTORY_LIVE", "LIVE_ONLY"]);
  assert.equal(strategyRunProfile(matrix, "host", "python")?.reason, "FLAG_DISABLED");
  assert.equal(strategyRunProfile(matrix, "native", "python"), null);
  manager.dispose();
});

test("the capability contract requires a reason exactly when a profile is unavailable", () => {
  const matrix = structuredClone(MATRIX) as { profiles: Record<string, unknown>[] };
  matrix.profiles[0] = { ...matrix.profiles[0], available: false, reason: null };
  assert.throws(() => parseStrategyRunCapabilities(matrix), StrategyRunContractError);
});
