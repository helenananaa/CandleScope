test("a run is watched through the facade stream and counted while it streams", async () => {
  let release: (() => void) | undefined;
  const manager = new StrategyDataManager(api({
    async watchStrategyRun(runId, signal, onStatus) {
      const terminal = { ...structuredClone(STATUS) as object, run_id: runId } as Parameters<NonNullable<typeof onStatus>>[0];
      onStatus?.(terminal, null);
      await new Promise<void>((resolve) => { release = resolve; });
      signal?.throwIfAborted();
      return terminal;
    },
  }));
  const seen: string[] = [];
  const watching = manager.watchRun("bt_1", (status) => seen.push(status.state));
  await new Promise((resolve) => setTimeout(resolve, 0));
  assert.equal(manager.diagnostics().streams, 1);
  release?.();
  assert.equal((await watching).run_id, "bt_1");
  assert.deepEqual(seen, ["COMPLETED"]);
  assert.equal(manager.diagnostics().streams, 0);
  await assert.rejects(new StrategyDataManager(api()).watchRun("bt_1"), /unavailable/i);
  manager.dispose();
});

// -- P2c: native runs and host-run following go through the manager ----------

type NativeClient = ConstructorParameters<typeof StrategyDataManager>[2];
type WatchedStatus = Awaited<ReturnType<NonNullable<StrategyDataApi["watchStrategyRun"]>>>;

function status(runId: string, state: string, sourceState = state): WatchedStatus {
  const terminal = ["COMPLETED", "FAILED", "CANCELLED"].includes(state);
  return parseStrategyRunStatus({ ...structuredClone(STATUS) as object, run_id: runId, state, source_state: sourceState,
    terminal, result_available: state === "COMPLETED" });
}

function watching(runId: string, states: Array<[string, string?]>): Partial<StrategyDataApi> {
  return {
    async watchStrategyRun(id, _signal, onStatus) {
      assert.equal(id, runId);
      const statuses = states.map(([state, source]) => status(runId, state, source));
      for (const value of statuses) onStatus?.(value, null);
      return statuses.at(-1)!;
    },
  };
}

test("native runs are created, listed, read and cancelled through the manager's client", async () => {
  const calls: string[] = [];
  const run = (runId: string, state = "COMPLETED") => ({ run_id: runId, state, execution_mode: "CANDLESCOPE", created_at_ms: 1 });
  const client = {
    async create(mode, _body, key) { calls.push(`create:${mode}:${key}`); return run("native_new", "QUEUED"); },
    async get(mode, runId) { calls.push(`get:${mode}:${runId}`); if (runId === "native_gone") throw new Error("gone"); return run(runId); },
    async list(mode) { calls.push(`list:${mode}`); return [run("native_a")]; },
    async cancel(mode, runId) { calls.push(`cancel:${mode}:${runId}`); return run(runId, "CANCELLED"); },
  } as NativeClient;
  const manager = new StrategyDataManager(api(), undefined, client);
  assert.equal((await manager.createNativeRun("CANDLESCOPE", {}, "key")).run_id, "native_new");
  assert.deepEqual((await manager.listNativeRuns("NATIVE", ["native_a", "native_b", "native_gone"])).map((item) => item.run_id),
    ["native_a", "native_b"], "listed runs plus readable saved ones");
  assert.equal((await manager.cancelNativeRun("NATIVE", "native_a")).state, "CANCELLED");
  assert.deepEqual(calls, ["create:CANDLESCOPE:key", "list:NATIVE", "get:NATIVE:native_b", "get:NATIVE:native_gone", "cancel:NATIVE:native_a"]);
  manager.dispose();
  await assert.rejects(manager.loadNativeRun("NATIVE", "native_a"), /closed/);
});

test("a native run is followed by stream and its finished record is read once", async () => {
  const reads: string[] = [];
  const queued = { run_id: "native_1", state: "QUEUED", execution_mode: "CANDLESCOPE", created_at_ms: 1 } as Parameters<StrategyDataManager["followNativeRun"]>[0];
  const client = { async get(mode, runId) { reads.push(`${mode}:${runId}`); return { ...queued, state: "COMPLETED", result: {} }; } } as NativeClient;
  const manager = new StrategyDataManager(api(watching("native_1", [["QUEUED"], ["RUNNING"], ["RUNNING"], ["COMPLETED"]])), undefined, client);
  const seen: string[] = [];
  const finished = await manager.followNativeRun(queued, (run) => seen.push(run.state));
  assert.deepEqual(seen, ["RUNNING", "COMPLETED"]);
  assert.equal(finished.state, "COMPLETED");
  assert.deepEqual(reads, ["CANDLESCOPE:native_1"]);
  assert.equal(manager.diagnostics().streams, 0);
  const mismatch = new StrategyDataManager(api(watching("native_1", [["FAILED", "INTERRUPTED"]])), undefined, client);
  await assert.rejects(mismatch.followNativeRun(queued, () => {}), /differs/);
  manager.dispose();
  mismatch.dispose();
});

test("a host run is followed by stream and a failed run is a result, not an error", async () => {
  const record = (state: string) => ({ run_id: "bt_1", state, failure_code: state === "FAILED" ? "PROVIDER_CRASH" : null }) as never;
  let reads = 0;
  const manager = new StrategyDataManager(api({
    ...watching("bt_1", [["QUEUED"], ["RUNNING"], ["FAILED"]]),
    async getRun() { reads += 1; return record(reads === 1 ? "QUEUED" : "FAILED"); },
  }));
  const seen: string[] = [];
  const finished = await manager.followHostRun("bt_1", (run) => seen.push(run.state));
  assert.deepEqual(seen, ["RUNNING"]);
  assert.equal((finished as { state: string }).state, "FAILED");
  assert.equal(reads, 2, "the record is read before watching and once at the end");
  const done = new StrategyDataManager(api({ async getRun() { return record("COMPLETED"); } }));
  assert.equal((await done.followHostRun("bt_1") as { state: string }).state, "COMPLETED", "a finished run is not watched");
  manager.dispose();
  done.dispose();
});

// -- P2d: forward runs ---------------------------------------------------------

const FORWARD = { ...structuredClone(HOST) as object, clock_policy: "FORWARD" };

test("a forward run's result is read every time and must be served as FORWARD", async () => {
  let reads = 0;
  const manager = new StrategyDataManager(api({ async getStrategyRunResult() { reads += 1; return structuredClone(FORWARD); } }));
  await manager.loadRunResult("continuous", "cs_1");
  await manager.loadRunResult("continuous", "cs_1");
  assert.equal(reads, 2, "a forward account changes with every commit, so it is never cached");
  assert.equal(manager.diagnostics().runResults, 0);
  const fixed = new StrategyDataManager(api({ async getStrategyRunResult() { return structuredClone(FORWARD); } }));
  await assert.rejects(fixed.loadRunResult("host", "bt_1"), /clock_policy/);
  const forward = new StrategyDataManager(api({ async getStrategyRunResult() { return structuredClone(HOST); } }));
  await assert.rejects(forward.loadRunResult("continuous", "cs_1"), /clock_policy/);
  for (const value of [manager, fixed, forward]) value.dispose();
});

test("a running forward run has a result; a running fixed run does not", () => {
  const live = { ...structuredClone(STATUS) as object, run_id: "cs_1", family: "continuous", clock_policy: "FORWARD",
    state: "RUNNING", source_state: "LIVE", terminal: false, result_available: true };
  assert.equal(parseStrategyRunStatus(live).result_available, true);
  assert.throws(() => parseStrategyRunStatus({ ...live, clock_policy: "FIXED" }), /result_available/);
});

// -- P3b: strategy versions ------------------------------------------------------

test("a status names its run's version, or null on backends before versions", () => {
  const status = parseStrategyRunStatus(structuredClone(STATUS));
  assert.match(status.version_hash ?? "", /^sha256:[0-9a-f]{64}$/);
  const { version_hash: _ignored, ...older } = structuredClone(STATUS) as Record<string, unknown>;
  assert.equal(parseStrategyRunStatus(older).version_hash, null);
  assert.throws(() => parseStrategyRunStatus({ ...(structuredClone(STATUS) as object), version_hash: "v1" }), /version_hash/);
});

test("a version is read through the manager and must be the one asked for; names point at versions", async () => {
  const hash = `sha256:${"a".repeat(64)}`;
  const version = { schema: "candlescope.strategy-version/1", version_hash: hash, language: "builtin", source: "builtin-sma-cross-v1",
    libraries: {}, runtime: { engine_version: "e" }, created_at_ms: 1, names: ["SMA"] };
  const calls: string[] = [];
  const manager = new StrategyDataManager(api({
    async getStrategyVersion(asked) { calls.push(`get:${asked}`); return structuredClone(version); },
    async nameStrategyVersion(name, asked) { calls.push(`name:${name}:${asked}`); return { name, version_hash: asked }; },
    async strategyVersionNames() { return { names: [{ name: "SMA", version_hash: hash, named_at_ms: 2 }] }; },
    async unnameStrategyVersion(name) { calls.push(`unname:${name}`); return { name, removed: true }; },
  }));
  assert.deepEqual((await manager.loadStrategyVersion(hash)).names, ["SMA"]);
  await assert.rejects(manager.loadStrategyVersion(`sha256:${"b".repeat(64)}`), StrategyRunContractError);
  assert.deepEqual(await manager.nameStrategyVersion("SMA", hash), { name: "SMA", version_hash: hash });
  assert.equal((await manager.listStrategyVersionNames())[0]?.version_hash, hash);
  assert.equal((await manager.unnameStrategyVersion("SMA")).removed, true);
  assert.deepEqual(calls, [`get:${hash}`, `get:sha256:${"b".repeat(64)}`, `name:SMA:${hash}`, "unname:SMA"]);
  await assert.rejects(new StrategyDataManager(api()).loadStrategyVersion(hash), /unavailable/i);
  manager.dispose();
});
