import {
  IndicatorStreamConnection,
  type IndicatorStreamConnectionOptions,
  type IndicatorStreamMessageContext,
  type IndicatorStreamSocket,
  type IndicatorStreamSubscription,
} from "./indicatorStreamConnection.js";
import type { IndicatorWsMessage } from "./indicatorTypes.js";
import { indicatorStreamSharingKey, localizeSharedIndicatorMessage, sharedIndicatorSubscribeMessage } from "./indicatorStreamSharing.js";

export interface IndicatorStreamIdentity {
  cellId: string;
  windowId: string;
  workspaceId: string;
}

export interface SharedIndicatorLogicalOptions {
  onConnectionReset?: IndicatorStreamConnectionOptions["onConnectionReset"];
  onError?: IndicatorStreamConnectionOptions["onError"];
  onMessage?: IndicatorStreamConnectionOptions["onMessage"];
  onParseError?: IndicatorStreamConnectionOptions["onParseError"];
  onSocketOpen?: IndicatorStreamConnectionOptions["onSocketOpen"];
  onSubscriptionPending?: IndicatorStreamConnectionOptions["onSubscriptionPending"];
}

export interface SharedIndicatorLogicalConnection {
  close(): void;
  forceResubscribe(): boolean;
  setSubscriptions(subscriptions: readonly IndicatorStreamSubscription[]): boolean;
  start(): void;
}

interface LogicalClient {
  closed: boolean;
  controller: SharedIndicatorLogicalConnection;
  id: number;
  identity: IndicatorStreamIdentity;
  options: SharedIndicatorLogicalOptions;
  started: boolean;
  subscriptions: Map<string, IndicatorStreamSubscription>;
}

interface WireSubscriptionOwner {
  id: string;
  localClientId: string;
  logical: LogicalClient;
  subscription: IndicatorStreamSubscription;
}

interface SubscriptionGroup {
  key: string;
  owners: Map<string, WireSubscriptionOwner>;
  wireClientId: string;
  cold: boolean;
  shard: PhysicalShard | null;
}

interface PhysicalShard {
  connection: IndicatorStreamConnection;
  index: number;
  groups: Map<string, SubscriptionGroup>;
  started: boolean;
}

export interface SharedIndicatorStreamCoordinatorOptions {
  maxSubscriptions?: number;
  socketFactory?: (url: string) => IndicatorStreamSocket;
  url: string | (() => string);
}

export interface SharedIndicatorStreamDiagnostics {
  logicalClients: number;
  logicalSubscriptions: number;
  sharedSubscriptions: number;
  deduplicatedSubscriptions: number;
  privateScriptSubscriptions: number;
  maxSubscriptions: number;
  physicalShards: number;
  shards: Array<{
    index: number;
    subscriptions: number;
  }>;
  subscriptions: number;
}

function validIdentityPart(value: string): boolean {
  return Boolean(value && value.trim() === value && [...value].every((character) => {
    const code = character.codePointAt(0) ?? 0;
    return code > 31 && code !== 127;
  }));
}

/** Validate the logical namespace. Physical IDs are generated by the manager. */
export function indicatorWireClientId(
  identity: IndicatorStreamIdentity,
  indicatorId: string,
): string | null {
  const parts = [identity.workspaceId, identity.windowId, identity.cellId, indicatorId];
  if (parts.some((part) => !validIdentityPart(part))) return null;
  const clientId = parts.map((part) => encodeURIComponent(part)).join("/");
  return clientId.length <= 256 ? clientId : null;
}

/**
 * Window-level broker: equivalent builtin consumers share a manager-owned
 * subscription. Script sessions remain private. Charts own neither physical
 * cancellation nor wire IDs; output/history stay in the existing chart caches.
 */
export class SharedIndicatorStreamCoordinator {
  private readonly url: SharedIndicatorStreamCoordinatorOptions["url"];
  private readonly socketFactory: ((url: string) => IndicatorStreamSocket) | undefined;
  private readonly logicalClients = new Map<number, LogicalClient>();
  private readonly groups = new Map<string, SubscriptionGroup>();
  private readonly shards: PhysicalShard[] = [];
  private readonly managerId = crypto.randomUUID();
  private nextLogicalId = 0;
  private nextWireId = 0;
  private nextShardId = 0;
  private maxSubscriptions: number;
  private disposed = false;
  private repack = false;
  private reconciling = false;
  private reconcileAgain = false;

  constructor({
    maxSubscriptions = 1,
    socketFactory,
    url,
  }: SharedIndicatorStreamCoordinatorOptions) {
    this.url = url;
    this.socketFactory = socketFactory;
    this.maxSubscriptions = Math.max(1, Math.floor(maxSubscriptions));
  }

  createLogicalConnection(
    identity: IndicatorStreamIdentity,
    options: SharedIndicatorLogicalOptions = {},
  ): SharedIndicatorLogicalConnection {
    this.nextLogicalId += 1;
    const logical = {
      closed: false,
      controller: null as unknown as SharedIndicatorLogicalConnection,
      id: this.nextLogicalId,
      identity: { ...identity },
      options,
      started: false,
      subscriptions: new Map<string, IndicatorStreamSubscription>(),
    };
    logical.controller = {
      start: () => {
        if (logical.closed || logical.started || this.disposed) return;
        logical.started = true;
        this.reconcile();
      },
      setSubscriptions: (subscriptions) => {
        if (logical.closed || this.disposed) return false;
        const next = new Map<string, IndicatorStreamSubscription>();
        for (const subscription of subscriptions) {
          if (!subscription.clientId || !subscription.signature) continue;
          if (!indicatorWireClientId(logical.identity, subscription.clientId)) continue;
          next.set(subscription.clientId, structuredClone(subscription));
        }
        logical.subscriptions = next;
        return this.reconcile();
      },
      forceResubscribe: () => {
        if (logical.closed || this.disposed) return false;
        let changed = false;
        for (const group of this.groups.values()) {
          if ([...group.owners.values()].some((owner) => owner.logical === logical)) {
            this.rotate(group);
            changed = true;
          }
        }
        return changed && this.reconcile();
      },
      close: () => {
        if (logical.closed) return;
        logical.closed = true;
        logical.subscriptions.clear();
        this.logicalClients.delete(logical.id);
        this.reconcile();
      },
    };
    this.logicalClients.set(logical.id, logical);
    return logical.controller;
  }

  setMaxSubscriptions(maxSubscriptions: number): void {
    const next = Math.max(1, Math.floor(maxSubscriptions));
    if (next === this.maxSubscriptions || this.disposed) return;
    this.maxSubscriptions = next;
    this.repack = true;
    this.reconcile();
  }

  diagnostics(): SharedIndicatorStreamDiagnostics {
    const groups = [...this.groups.values()];
    const logicalSubscriptions = groups.reduce((total, group) => total + group.owners.size, 0);
    return {
      logicalClients: [...this.logicalClients.values()].filter((logical) => (
        logical.started && !logical.closed
      )).length,
      logicalSubscriptions,
      sharedSubscriptions: groups.filter(group => group.owners.size > 1).length,
      deduplicatedSubscriptions: logicalSubscriptions - groups.length,
      privateScriptSubscriptions: groups.filter(group => group.owners.values().next().value?.subscription.message.kind === "script").length,
      maxSubscriptions: this.maxSubscriptions,
      physicalShards: this.shards.length,
      shards: this.shards.map((shard) => ({
        index: shard.index,
        subscriptions: shard.groups.size,
      })),
      subscriptions: groups.length,
    };
  }

  closeAll(): void {
    if (this.disposed) return;
    this.disposed = true;
    for (const logical of this.logicalClients.values()) {
      logical.closed = true;
      logical.subscriptions.clear();
    }
    this.logicalClients.clear();
    this.groups.clear();
    for (const shard of this.shards) shard.groups.clear();
    this.shards.splice(0).forEach((shard) => shard.connection.close());
  }

  private wireId(): string { return `indicator-stream:${this.managerId}:${++this.nextWireId}`; }

  private rotate(group: SubscriptionGroup): void {
    group.wireClientId = this.wireId();
    group.cold = true;
  }

  private collectGroups(): void {
    const desired = new Map<string, Map<string, WireSubscriptionOwner>>();
    for (const logical of this.logicalClients.values()) {
      if (logical.closed || !logical.started) continue;
      for (const [localClientId, subscription] of logical.subscriptions) {
        const id = `${logical.id}/${localClientId}`;
        const key = indicatorStreamSharingKey(subscription,
          [logical.identity.workspaceId, logical.identity.windowId], id);
        let owners = desired.get(key);
        if (!owners) { owners = new Map(); desired.set(key, owners); }
        owners.set(id, { id, localClientId, logical, subscription });
      }
    }
    for (const [key, group] of this.groups) {
      if (desired.has(key)) continue;
      group.shard?.groups.delete(key);
      this.groups.delete(key);
    }
    for (const [key, owners] of desired) {
      let group = this.groups.get(key);
      if (!group) {
        group = { key, owners, wireClientId: this.wireId(), cold: false, shard: null };
        this.groups.set(key, group);
      } else {
        // The protocol has no ACK replay/bootstrap operation for a new owner.
        // Obtain a fresh cold ACK without resetting unrelated subscriptions.
        // The new wire ID also fences delayed ACK/preview frames from the old
        // membership, including remove/re-add and configuration A/B/A races.
        const previousOwners = group.owners;
        if ([...owners.keys()].some(id => !previousOwners.has(id))) this.rotate(group);
        group.owners = owners;
      }
    }
  }

  private reconcile(): boolean {
    if (this.disposed) return false;
    if (this.reconciling) { this.reconcileAgain = true; return false; }
    this.reconciling = true;
    let synced = false;
    try {
      do {
        this.reconcileAgain = false;
        this.collectGroups();
        if (this.repack) {
          this.repack = false;
          for (const group of this.groups.values()) group.shard = null;
          for (const shard of this.shards) shard.groups.clear();
        }
        for (const group of this.groups.values()) {
          if (group.shard) continue;
          let shard = this.shards.find(item => item.groups.size < this.maxSubscriptions);
          if (!shard) { shard = this.createShard(this.nextShardId++); this.shards.push(shard); }
          group.shard = shard;
          shard.groups.set(group.key, group);
        }
        // Ordinary joins/leaves retain all surviving shard assignments. Only a
        // capability change repacks them; removing an unrelated group cannot
        // restart another chart's stream or its private Pine session.
        for (let index = this.shards.length - 1; index >= 0; index -= 1) {
          if (this.shards[index]!.groups.size === 0) this.shards.splice(index, 1)[0]!.connection.close();
        }
        synced = this.groups.size === 0 || synced;
        for (const shard of [...this.shards]) {
          const subscriptions = [...shard.groups.values()].map(group => ({
            clientId: group.wireClientId, signature: group.key,
            message: sharedIndicatorSubscribeMessage([...group.owners.values()].map(owner => owner.subscription), group.wireClientId, group.cold),
          }));
          synced = shard.connection.setSubscriptions(subscriptions) || synced;
          if (!shard.started && !this.disposed) { shard.started = true; shard.connection.start(); }
        }
      } while (this.reconcileAgain && !this.disposed);
    } finally { this.reconciling = false; }
    return synced;
  }

  private notify(logical: LogicalClient, callback: () => void): void {
    if (logical.closed || this.disposed) return;
    try { callback(); }
    catch (error) {
      // A broken consumer must not prevent fanout or transport reconciliation.
      try { logical.options.onError?.(error); } catch { /* isolated consumer */ }
    }
  }

  private currentOwner(group: SubscriptionGroup, owner: WireSubscriptionOwner): boolean {
    return this.groups.get(group.key) === group && group.owners.has(owner.id)
      && !owner.logical.closed
      && owner.logical.subscriptions.get(owner.localClientId)?.signature === owner.subscription.signature;
  }

  private groupForWire(shard: PhysicalShard, wireClientId: string): SubscriptionGroup | undefined {
    return [...shard.groups.values()].find(group => group.wireClientId === wireClientId);
  }

  private createShard(index: number): PhysicalShard {
    const shard: PhysicalShard = {
      connection: null as unknown as IndicatorStreamConnection,
      index, groups: new Map(), started: false,
    };
    const notifyOwners = (callback: (logical: LogicalClient) => void) => {
      const logicals = new Set([...shard.groups.values()].flatMap(group => [...group.owners.values()].map(owner => owner.logical)));
      for (const logical of logicals) {
        if ([...shard.groups.values()].some(group => [...group.owners.values()].some(owner => owner.logical === logical))) {
          this.notify(logical, () => callback(logical));
        }
      }
    };
    shard.connection = new IndicatorStreamConnection({
      url: typeof this.url === "function" ? this.url() : this.url,
      ...(this.socketFactory ? { socketFactory: this.socketFactory } : {}),
      onConnectionReset: reason => notifyOwners(logical => logical.options.onConnectionReset?.(reason)),
      onError: error => notifyOwners(logical => logical.options.onError?.(error)),
      onMessage: (message, context) => this.dispatchMessage(shard, message, context),
      onParseError: error => notifyOwners(logical => logical.options.onParseError?.(error)),
      onSocketOpen: context => notifyOwners(logical => logical.options.onSocketOpen?.(context)),
      onSubscriptionPending: (wireClientId, attempts) => {
        const group = this.groupForWire(shard, wireClientId);
        if (!group) return;
        for (const owner of [...group.owners.values()]) {
          if (group.wireClientId !== wireClientId || !this.currentOwner(group, owner)) continue;
          this.notify(owner.logical, () => owner.logical.options.onSubscriptionPending?.(owner.localClientId, attempts));
        }
      },
    });
    return shard;
  }

  private dispatchMessage(shard: PhysicalShard, message: IndicatorWsMessage, context: IndicatorStreamMessageContext): void {
    const wireClientId = message.clientId;
    if (!wireClientId) return;
    const group = this.groupForWire(shard, wireClientId);
    if (!group || context.subscriptionSignature !== group.key) return;
    // Cold subscriptions are acknowledged with history_required; the existing
    // per-chart HTTP hydration owns historical readiness, not a cached WS ACK.
    if (message.type === "indicator.subscribed" && message.ok !== false) group.cold = false;
    for (const owner of [...group.owners.values()]) {
      if (group.wireClientId !== wireClientId || !this.currentOwner(group, owner)) continue;
      this.notify(owner.logical, () => owner.logical.options.onMessage?.(
        localizeSharedIndicatorMessage(message, owner.subscription),
        { ...context, subscriptionSignature: owner.subscription.signature },
      ));
    }
    if (message.type === "indicator.subscribed") this.reconcile();
  }
}
